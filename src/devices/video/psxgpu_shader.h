/***************************************************************************

    psxgpu_shader.h

    Pixel pipeline of the PS1 GPU host-GPU path, as a gpu_shader_module
    (see osd/interface/gpuengine.h). The texture sheet is the whole 1024 x
    vram_height VRAM as raw 16-bit words (binding "vram"); texture page,
    CLUT, texture window and interleave addressing follow the rules of the PS1 GPU
    and are evaluated per fragment from the primitive state
    record. VARIANT selects the semi-transparency pass: 0 = all texels,
    1 = only texels with the STP bit set, 2 = only texels with it clear.

    Varyings: v0-v3 vertex colour (a PS1 modulation factor, 0.5 = neutral),
    v4-v5 texel coordinates, v6-v9 the texel rectangle (u_min, v_min, u_max,
    v_max) filtered taps are clamped to.

    Primitive state record, 13 words: textured, texture filter mode
    (0 nearest, 1 bilinear, 2 trilinear, 3 three-point), texture page mode
    (0 4bpp, 1 8bpp, 2 15bpp), page x, page y, CLUT x, CLUT y, texture
    window active, window and-u, and-v, offset-u, offset-v, interleave.

***************************************************************************/
#ifndef MAME_VIDEO_PSXGPU_SHADER_H
#define MAME_VIDEO_PSXGPU_SHADER_H

#pragma once

constexpr int PSXGPU_SHADER_STATE_WORDS = 13;
constexpr int PSXGPU_SHADER_VARYINGS = 10;

constexpr char PSXGPU_FRAGMENT_SOURCE[] =
	"vec4 g_color;\n"
	"vec2 g_uv;\n"
	"vec4 g_uv_clamp;\n"
	"int s_textured, s_texfilter, s_tp, s_tx, s_ty, s_clutx, s_cluty;\n"
	"int s_tw_active, s_tw_andu, s_tw_andv, s_tw_offu, s_tw_offv, s_interleave, s_vram_height;\n"
	"void load_state() {\n"
	"    g_color = vec4(v0, v1, v2, v3);\n"
	"    g_uv = vec2(v4, v5);\n"
	"    g_uv_clamp = vec4(v6, v7, v8, v9);\n"
	"    s_textured = state(0);\n"
	"    s_texfilter = state(1);\n"
	"    s_tp = state(2);\n"
	"    s_tx = state(3);\n"
	"    s_ty = state(4);\n"
	"    s_clutx = state(5);\n"
	"    s_cluty = state(6);\n"
	"    s_tw_active = state(7);\n"
	"    s_tw_andu = state(8);\n"
	"    s_tw_andv = state(9);\n"
	"    s_tw_offu = state(10);\n"
	"    s_tw_offv = state(11);\n"
	"    s_interleave = state(12);\n"
	"    s_vram_height = vram_size().y;\n"
	"}\n"
	"uint fetch_bgr(int u, int v) {\n"
	"    int offu = 0;\n"
	"    int offv = 0;\n"
	"    if (s_tw_active != 0) {\n"
	"        u = u & s_tw_andu;\n"
	"        v = v & s_tw_andv;\n"
	"        offu = s_tw_offu;\n"
	"        offv = s_tw_offv;\n"
	"    }\n"
	"    int clutrow = s_cluty % s_vram_height;\n"
	"    if (s_interleave != 0 && s_tp != 2) {\n"
	"        int xi;\n"
	"        int yi;\n"
	"        uint idx;\n"
	"        if (s_tp == 0) {\n"
	"            xi = ((u >> 2) & ~0x3c) + ((v << 2) & 0x3c);\n"
	"            yi = (v & ~0xf) + ((u >> 4) & 0xf);\n"
	"        } else {\n"
	"            xi = ((u >> 1) & ~0x78) + ((u << 2) & 0x40) + ((v << 3) & 0x38);\n"
	"            yi = (v & ~0x7) + ((u >> 5) & 0x7);\n"
	"        }\n"
	"        int irow = (s_ty + offv + yi) % s_vram_height;\n"
	"        int icol = (s_tx + ((s_tp == 0) ? (offu >> 2) : (offu >> 1)) + xi) & 1023;\n"
	"        uint iword = texelFetch(vram, ivec2(icol, irow), 0).r;\n"
	"        if (s_tp == 0)\n"
	"            idx = (iword >> uint((u & 3) << 2)) & 0x0Fu;\n"
	"        else\n"
	"            idx = (iword >> uint((u & 1) << 3)) & 0xFFu;\n"
	"        int iclutcol = (s_clutx + int(idx)) & 1023;\n"
	"        return texelFetch(vram, ivec2(iclutcol, clutrow), 0).r;\n"
	"    }\n"
	"    u += offu;\n"
	"    v += offv;\n"
	"    int row = (s_ty + v) % s_vram_height;\n"
	"    uint bgr;\n"
	"    if (s_tp == 0) {\n"
	"        int col = (s_tx + (u >> 2)) & 1023;\n"
	"        uint word = texelFetch(vram, ivec2(col, row), 0).r;\n"
	"        uint idx = (word >> uint((u & 3) << 2)) & 0x0Fu;\n"
	"        int clutcol = (s_clutx + int(idx)) & 1023;\n"
	"        bgr = texelFetch(vram, ivec2(clutcol, clutrow), 0).r;\n"
	"    } else if (s_tp == 1) {\n"
	"        int col = (s_tx + (u >> 1)) & 1023;\n"
	"        uint word = texelFetch(vram, ivec2(col, row), 0).r;\n"
	"        uint idx = (word >> uint((u & 1) << 3)) & 0xFFu;\n"
	"        int clutcol = (s_clutx + int(idx)) & 1023;\n"
	"        bgr = texelFetch(vram, ivec2(clutcol, clutrow), 0).r;\n"
	"    } else {\n"
	"        int col = (s_tx + u) & 1023;\n"
	"        bgr = texelFetch(vram, ivec2(col, row), 0).r;\n"
	"    }\n"
	"    return bgr;\n"
	"}\n"
	"vec4 decode_texel(int u, int v) {\n"
	"    uint bgr = fetch_bgr(u, v);\n"
	"    if (bgr == 0u) return vec4(0.0);\n"
	"    uint r8 = (bgr & 0x1Fu) << 3;\n"
	"    uint g8 = ((bgr >> 5) & 0x1Fu) << 3;\n"
	"    uint b8 = ((bgr >> 10) & 0x1Fu) << 3;\n"
	"    return vec4(vec3(float(r8), float(g8), float(b8)) / 255.0, 1.0);\n"
	"}\n"
	"vec4 sample_bilinear(vec2 uv, int step, ivec2 cmin, ivec2 cmax) {\n"
	"    vec2 guv = uv / float(step) - 0.5;\n"
	"    ivec2 base = ivec2(floor(guv)) * step;\n"
	"    vec2 frac = fract(guv);\n"
	"    ivec2 t00 = clamp(base, cmin, cmax);\n"
	"    ivec2 t10 = clamp(base + ivec2(step, 0), cmin, cmax);\n"
	"    ivec2 t01 = clamp(base + ivec2(0, step), cmin, cmax);\n"
	"    ivec2 t11 = clamp(base + ivec2(step, step), cmin, cmax);\n"
	"    vec4 c00 = decode_texel(t00.x, t00.y);\n"
	"    vec4 c10 = decode_texel(t10.x, t10.y);\n"
	"    vec4 c01 = decode_texel(t01.x, t01.y);\n"
	"    vec4 c11 = decode_texel(t11.x, t11.y);\n"
	"    float w00 = (1.0 - frac.x) * (1.0 - frac.y) * c00.a;\n"
	"    float w10 = frac.x * (1.0 - frac.y) * c10.a;\n"
	"    float w01 = (1.0 - frac.x) * frac.y * c01.a;\n"
	"    float w11 = frac.x * frac.y * c11.a;\n"
	"    float wsum = w00 + w10 + w01 + w11;\n"
	"    if (wsum <= 0.0) return vec4(0.0);\n"
	"    return vec4((c00.rgb * w00 + c10.rgb * w10 + c01.rgb * w01 + c11.rgb * w11) / wsum, 1.0);\n"
	"}\n"
	"vec4 sample_3point(vec2 uv, ivec2 cmin, ivec2 cmax) {\n"
	"    vec2 guv = uv - 0.5;\n"
	"    ivec2 base = ivec2(floor(guv));\n"
	"    vec2 frac = fract(guv);\n"
	"    ivec2 t00 = clamp(base, cmin, cmax);\n"
	"    ivec2 t10 = clamp(base + ivec2(1, 0), cmin, cmax);\n"
	"    ivec2 t01 = clamp(base + ivec2(0, 1), cmin, cmax);\n"
	"    ivec2 t11 = clamp(base + ivec2(1, 1), cmin, cmax);\n"
	"    vec4 c00 = decode_texel(t00.x, t00.y);\n"
	"    vec4 c10 = decode_texel(t10.x, t10.y);\n"
	"    vec4 c01 = decode_texel(t01.x, t01.y);\n"
	"    vec4 c11 = decode_texel(t11.x, t11.y);\n"
	"    float w00, w10, w01, w11;\n"
	"    if (frac.x + frac.y <= 1.0) {\n"
	"        w00 = 1.0 - frac.x - frac.y; w10 = frac.x; w01 = frac.y; w11 = 0.0;\n"
	"    } else {\n"
	"        w11 = frac.x + frac.y - 1.0; w10 = 1.0 - frac.y; w01 = 1.0 - frac.x; w00 = 0.0;\n"
	"    }\n"
	"    w00 *= c00.a; w10 *= c10.a; w01 *= c01.a; w11 *= c11.a;\n"
	"    float wsum = w00 + w10 + w01 + w11;\n"
	"    if (wsum <= 0.0) return vec4(0.0);\n"
	"    return vec4((c00.rgb * w00 + c10.rgb * w10 + c01.rgb * w01 + c11.rgb * w11) / wsum, 1.0);\n"
	"}\n"
	"void texel_stp(out bool stp, out float opacity) {\n"
	"    if (s_texfilter == 0) {\n"
	"        stp = (fetch_bgr(int(g_uv.x), int(g_uv.y)) & 0x8000u) != 0u;\n"
	"        opacity = 1.0;\n"
	"        return;\n"
	"    }\n"
	"    ivec2 cmin = ivec2(floor(g_uv_clamp.xy));\n"
	"    ivec2 cmax = ivec2(floor(g_uv_clamp.zw));\n"
	"    vec2 guv = g_uv - 0.5;\n"
	"    ivec2 base = ivec2(floor(guv));\n"
	"    vec2 fr = fract(guv);\n"
	"    ivec2 t00 = clamp(base, cmin, cmax);\n"
	"    ivec2 t10 = clamp(base + ivec2(1, 0), cmin, cmax);\n"
	"    ivec2 t01 = clamp(base + ivec2(0, 1), cmin, cmax);\n"
	"    ivec2 t11 = clamp(base + ivec2(1, 1), cmin, cmax);\n"
	"    uint b00 = fetch_bgr(t00.x, t00.y);\n"
	"    uint b10 = fetch_bgr(t10.x, t10.y);\n"
	"    uint b01 = fetch_bgr(t01.x, t01.y);\n"
	"    uint b11 = fetch_bgr(t11.x, t11.y);\n"
	"    float w00, w10, w01, w11;\n"
	"    if (s_texfilter == 3) {\n"
	"        if (fr.x + fr.y <= 1.0) {\n"
	"            w00 = 1.0 - fr.x - fr.y; w10 = fr.x; w01 = fr.y; w11 = 0.0;\n"
	"        } else {\n"
	"            w11 = fr.x + fr.y - 1.0; w10 = 1.0 - fr.y; w01 = 1.0 - fr.x; w00 = 0.0;\n"
	"        }\n"
	"    } else {\n"
	"        w00 = (1.0 - fr.x) * (1.0 - fr.y); w10 = fr.x * (1.0 - fr.y);\n"
	"        w01 = (1.0 - fr.x) * fr.y; w11 = fr.x * fr.y;\n"
	"    }\n"
	"    opacity = w00 * (b00 != 0u ? 1.0 : 0.0) + w10 * (b10 != 0u ? 1.0 : 0.0)\n"
	"            + w01 * (b01 != 0u ? 1.0 : 0.0) + w11 * (b11 != 0u ? 1.0 : 0.0);\n"
	"    float sv = w00 * float((b00 >> 15) & 1u) + w10 * float((b10 >> 15) & 1u)\n"
	"             + w01 * float((b01 >> 15) & 1u) + w11 * float((b11 >> 15) & 1u);\n"
	"    stp = floor(sv + 0.5) >= 1.0;\n"
	"}\n"
	"bool shade(out vec4 color) {\n"
	"    load_state();\n"
	"    if (s_textured != 0) {\n"
	"        vec4 texel;\n"
	"        if (s_texfilter == 0) {\n"
	"            texel = decode_texel(int(g_uv.x), int(g_uv.y));\n"
	"        } else if (s_texfilter == 1) {\n"
	"            ivec2 cmin = ivec2(floor(g_uv_clamp.xy));\n"
	"            ivec2 cmax = ivec2(floor(g_uv_clamp.zw));\n"
	"            texel = sample_bilinear(g_uv, 1, cmin, cmax);\n"
	"        } else if (s_texfilter == 2) {\n"
	"            ivec2 cmin = ivec2(floor(g_uv_clamp.xy));\n"
	"            ivec2 cmax = ivec2(floor(g_uv_clamp.zw));\n"
	"            vec4 lvl0 = sample_bilinear(g_uv, 1, cmin, cmax);\n"
	"            vec4 lvl1 = sample_bilinear(g_uv, 2, cmin, cmax);\n"
	"            float density = max(length(dFdx(g_uv)), length(dFdy(g_uv)));\n"
	"            float t = clamp(density - 1.0, 0.0, 1.0);\n"
	"            if (lvl0.a <= 0.0) { texel = lvl1; }\n"
	"            else if (lvl1.a <= 0.0) { texel = lvl0; }\n"
	"            else { texel = vec4(mix(lvl0.rgb, lvl1.rgb, t), 1.0); }\n"
	"        } else {\n"
	"            ivec2 cmin = ivec2(floor(g_uv_clamp.xy));\n"
	"            ivec2 cmax = ivec2(floor(g_uv_clamp.zw));\n"
	"            texel = sample_3point(g_uv, cmin, cmax);\n"
	"        }\n"
	"        if (texel.a <= 0.0) return false;\n"
	"        if (VARIANT != 0) {\n"
	"            bool stp; float stp_opacity;\n"
	"            texel_stp(stp, stp_opacity);\n"
	"            if (stp_opacity < 0.5) return false;\n"
	"            if (VARIANT == 1 && !stp) return false;\n"
	"            if (VARIANT == 2 && stp) return false;\n"
	"        }\n"
	"        color = vec4(clamp(texel.rgb * (g_color.rgb * 2.0), 0.0, 1.0), 1.0);\n"
	"    } else {\n"
	"        color = g_color;\n"
	"    }\n"
	"    return true;\n"
	"}\n";

#endif // MAME_VIDEO_PSXGPU_SHADER_H
